import { useEffect, useMemo, useState } from "react";
import { ShieldCheck } from "lucide-react";
import { pct, rs, sipThroughCrash, type Engine } from "../engine";
import type { Profile } from "../store";
import { AreaChart, Count } from "../ui";
import type { Results, Track } from "../App";
import { behaviourGap } from "../analytics";

const PLEDGES = [
  "I will not sell in panic during a crash",
  "I will keep my SIP running when markets fall",
  "I will check my plan, not the news, before acting",
];

export function Crash({ eng, profile, r, update, track }: { eng: Engine; profile: Profile; r: Results; update: (p: Partial<Profile>) => void; track: Track }) {
  useEffect(() => { track("crash"); }, [track]);
  const gap = useMemo(() => behaviourGap(eng, profile.holdings, Math.max(profile.sip, 1000)), [eng, profile.holdings, profile.sip]);
  const [showGap, setShowGap] = useState(false);
  const total = profile.holdings.reduce((a, h) => a + h.amount, 0);
  const c = r.crash, h = r.hist;
  const within = Math.abs(c.troughBad) <= profile.tolerance;
  const [ticks, setTicks] = useState<boolean[]>(PLEDGES.map(() => profile.crashPlan));
  const sipRes = useMemo(() => sipThroughCrash(eng, profile.holdings, Math.max(profile.sip, 1000)), [eng, profile.holdings, profile.sip]);
  const weeks = c.p50.map((_, i) => (i === 0 ? "now" : `wk ${i}`));
  const V = (a: number[]) => a.map((v) => v * total);
  const histLabels = h.labels.map((l) => (l === "start" ? "2010" : l.slice(0, 4)));
  const histVals = h.value.map((v) => v * 100000);
  const months = Array.from({ length: sipRes.months + 1 }, (_, i) => (i % 12 === 0 ? `Yr ${i / 12}` : `m${i}`));

  return (
    <>
    <div className="pagehead"><div><div className="eyebrow">What a severe crash would do to your {rs(total)}</div><h1 className="title">Crash test</h1></div></div>
    <div className="grid">
      <div className="card hero c12">
        <div className="row" style={{ gap: 40 }}>
          <div className="kpi"><span>Bad-case value after a severe crash</span><b className="badtext" style={{ fontSize: 52, letterSpacing: "-0.045em" }}>
            <Count value={total * (1 + c.troughBad)} fmt={(v) => rs(v)} /></b></div>
          <div className="kpi"><span>Drop</span><b style={{ fontSize: 32 }}>{rs(c.lossBadRs)}</b></div>
          <div className="kpi"><span>Bad case</span><b style={{ fontSize: 32 }}>{pct(c.troughBad)}</b></div>
          <div className="kpi"><span>Typical crash</span><b style={{ fontSize: 32 }}>{pct(c.troughMedian)}</b></div>
          <span className={`pill ${within ? "good" : "bad"}`} style={{ marginLeft: "auto" }}>{within ? `Within your ${pct(-profile.tolerance)} limit` : `Beyond your ${pct(-profile.tolerance)} limit`}</span>
        </div>
        <p className="muted" style={{ marginTop: 14 }}>Worst 1-in-20 quarters generated by the VORTEX-AI model. Real crashes can be deeper.</p>
      </div>

      <div className="card c8 delay1">
        <div className="row between"><h3>The next 12 weeks in a crash</h3>
          <div className="legend"><span><i style={{ background: "#e2475a" }} />typical crash</span><span><i style={{ background: "rgba(226,71,90,.35)" }} />range</span>
            <span><i style={{ background: "#c47c0c" }} />a severe one</span></div></div>
        <AreaChart xLabels={weeks} fmt={(v) => rs(v)} hline={total} hlabel="today"
          bands={[{ lo: V(c.p10), hi: V(c.p90), color: "#e2475a", opacity: 0.3 }]}
          series={[{ values: V(c.worstPath), color: "#c47c0c", width: 1.8, label: "Severe" }, { values: V(c.p50), color: "#e2475a", width: 3, label: "Typical" }]} height={260} />
      </div>

      <div className="card c4 delay2 stack">
        <h3>Your crash plan</h3>
        <p className="sub">People who decide <i>before</i> a crash are far less likely to sell at the bottom.</p>
        {PLEDGES.map((p, i) => (
          <button key={i} className={`list-row ${ticks[i] ? "chip on" : ""}`} style={{ width: "100%", textAlign: "left" }}
            onClick={() => setTicks((t) => t.map((x, j) => (j === i ? !x : x)))}>
            <span>{p}</span><span>{ticks[i] ? "✓" : ""}</span>
          </button>
        ))}
        <button className="btn" disabled={!ticks.every(Boolean) || profile.crashPlan} onClick={() => update({ crashPlan: true })}>
          <ShieldCheck size={16} /> {profile.crashPlan ? "Plan locked in" : "Lock in my plan"}</button>
      </div>

      <div className="card c7 delay3">
        <h3>Your mix through real history (₹1 lakh in Nov 2010)</h3>
        <AreaChart xLabels={histLabels} fmt={(v) => rs(v)} series={[{ values: histVals, color: "#a6d43a", width: 2.4, label: "Value" }]} height={220} />
        <div className="row" style={{ gap: 24 }}>
          <div className="kpi"><b className="badtext">{pct(h.worstDrop)}</b><span>worst fall ({h.worstFrom} → {h.worstTo})</span></div>
          <div className="kpi"><b>{h.recoverMonths === null ? "not yet" : `${h.recoverMonths} mo`}</b><span>to recover</span></div>
          {h.covidDrop !== null && <div className="kpi"><b className="badtext">{pct(h.covidDrop)}</b><span>COVID 2020 drop{h.covidRecover !== null ? `, back in ${h.covidRecover} mo` : ""}</span></div>}
          <div className="kpi"><b className="goodtext">{pct(h.upYears)}</b><span>of 12-month periods ended up</span></div>
        </div>
        <p className="muted">Real monthly returns of the stocks in your mix; funds use their measured market sensitivity. History flatters survivors.</p>
      </div>

      <div className="card c5 delay4">
        <h3>Should you stop your SIP in a crash?</h3>
        <AreaChart xLabels={months} fmt={(v) => rs(v)}
          series={[{ values: sipRes.stop, color: "#6b707b", width: 2, label: "Paused SIP for a year" },
                   { values: sipRes.keep, color: "#a6d43a", width: 3, label: "Kept SIP going" }]} height={200} />
        <p className="sub">Over 5 years after a crash, keeping your {rs(Math.max(profile.sip, 1000))} SIP running ends at <b className="goodtext">{rs(sipRes.keepFinal)}</b>
          {" "}vs <b>{rs(sipRes.stopFinal)}</b> if you pause for a year. You also buy units cheap while everyone else panics.</p>
        <p className="muted">Average over 600 simulated crash-then-recovery paths. Part of the gap is simply the extra 12 instalments.</p>
      </div>
      {gap && (
        <div className="card c12 delay4">
          <div className="row between"><h3>The behaviour gap: what panic-selling in 2020 would have cost you</h3>
            {!showGap && <button className="btn small" onClick={() => { setShowGap(true); track("gap"); }}>Reveal</button>}</div>
          {showGap ? (
            <>
              <div className="row" style={{ gap: 36, margin: "12px 0" }}>
                <div className="kpi"><span>Stayed invested</span><b className="goodtext">{rs(gap.stayedEnd)}</b></div>
                <div className="kpi"><span>Sold at the bottom ({gap.sellAt}), came back {gap.backAt}</span><b>{rs(gap.panickedEnd)}</b></div>
                <div className="kpi"><span>Cost of panicking</span><b className="badtext">{rs(gap.cost)}</b></div>
              </div>
              <AreaChart xLabels={gap.months} fmt={(v) => rs(v)} height={210}
                series={[{ values: gap.panicked, color: "#6b707b", width: 2, label: "Panicked" }, { values: gap.stayed, color: "#a6d43a", width: 2.4, label: "Stayed" }]} />
              <p className="muted">Real monthly history of your mix with a {rs(Math.max(profile.sip, 1000))} SIP from Jan 2019. Industry studies put the average
                Indian equity investor about 5 percentage points a year behind the funds they own, mostly from moves like this.</p>
            </>
          ) : <p className="sub" style={{ marginTop: 10 }}>Replay March 2020 with your own mix: one person holds on, the other sells at the low and waits for "things to calm down".</p>}
        </div>
      )}
    </div>
    </>
  );
}
