import { useState } from "react";
import { ArrowRight, Shield, Scale, Rocket, Sparkles } from "lucide-react";
import { rs, type Engine } from "../engine";
import { GOALS, starter, type Profile } from "../store";
import { Slider } from "../ui";
import { LogoMark, Wordmark } from "../brand";

export function Onboarding({ eng, onDone }: { eng: Engine; onDone: (p: Profile) => void }) {
  const [step, setStep] = useState(0);
  const [name, setName] = useState("");
  const [gk, setGk] = useState(GOALS[0]);
  const [goal, setGoal] = useState(GOALS[0].amount);
  const [years, setYears] = useState(GOALS[0].years);
  const [start, setStart] = useState(200000);
  const [sip, setSip] = useState(15000);
  const [tol, setTol] = useState(0.2);
  const [mix, setMix] = useState<"careful" | "balanced" | "bold">("balanced");
  const [building, setBuilding] = useState(false);

  const finish = () => {
    setBuilding(true);
    setTimeout(() => onDone({
      name: name.trim() || "Friend", goalKind: gk.k, goal, years, start, sip, stepUp: 0.05, inflation: 0.06, tolerance: tol,
      emergency: false, crashPlan: false, holdings: starter(eng, mix, Math.max(start, 100000)),
    }), 1400);
  };

  if (building) return (
    <div className="onb"><div className="panel" style={{ textAlign: "center" }}>
      <div style={{ display: "inline-block", margin: "0 auto 18px", animation: "spin 2.4s linear infinite" }}><LogoMark size={70} /></div>
      <h1 className="title">Simulating <span className="gradtext">thousands of futures</span>…</h1>
      <p className="sub">Including realistic crashes generated by our AI market model.</p>
    </div></div>
  );

  return (
    <div className="onb">
      <div className="panel">
        <div className="steps">{[0, 1, 2, 3].map((i) => <i key={i} className={i <= step ? "on" : ""} />)}</div>

        {step === 0 && (
          <div className="card hero stack">
            <Wordmark size={34} />
            <h1 className="title">See your money's <span className="gradtext">real future</span>, crashes included.</h1>
            <p className="sub">Most calculators pretend markets grow a smooth 12% a year. We simulate thousands of realistic
              futures, including crashes like 2020, so your plan holds up when it matters.</p>
            <div className="field"><label>What should we call you?</label>
              <input className="input" placeholder="Your name" value={name} onChange={(e) => setName(e.target.value)} autoFocus /></div>
            <button className="btn" onClick={() => setStep(1)}>Let's start <ArrowRight size={18} /></button>
          </div>
        )}

        {step === 1 && (
          <div className="card stack">
            <h1 className="title">What are you saving for?</h1>
            <div className="row">
              {GOALS.map((g) => (
                <button key={g.k} className={`chip ${gk.k === g.k ? "on" : ""}`}
                  onClick={() => { setGk(g); setGoal(g.amount); setYears(g.years); }}>
                  <span className="emoji">{g.emoji}</span>{g.label}
                </button>
              ))}
            </div>
            <Slider label="Amount you need (in today's money)" value={goal} min={100000} max={50000000} step={50000} onChange={setGoal} fmt={(v) => rs(v)} />
            <Slider label="In how many years?" value={years} min={1} max={35} step={1} onChange={setYears} fmt={(v) => `${v} yrs`} />
            <div className="row between"><button className="btn ghost" onClick={() => setStep(0)}>Back</button>
              <button className="btn" onClick={() => setStep(2)}>Next <ArrowRight size={18} /></button></div>
          </div>
        )}

        {step === 2 && (
          <div className="card stack">
            <h1 className="title">Your money today</h1>
            <Slider label="Already invested or saved" value={start} min={0} max={10000000} step={10000} onChange={setStart} fmt={(v) => rs(v)} />
            <Slider label="Monthly SIP you can invest" value={sip} min={0} max={300000} step={500} onChange={setSip} fmt={(v) => rs(v)} />
            <div className="field"><label>If your investments fell this much in a crash, could you sit tight without selling?</label>
              <div className="row">
                {[0.1, 0.2, 0.3, 0.4].map((t) => (
                  <button key={t} className={`chip ${tol === t ? "on" : ""}`} onClick={() => setTol(t)}>−{t * 100}%</button>
                ))}
              </div></div>
            <div className="row between"><button className="btn ghost" onClick={() => setStep(1)}>Back</button>
              <button className="btn" onClick={() => setStep(3)}>Next <ArrowRight size={18} /></button></div>
          </div>
        )}

        {step === 3 && (
          <div className="card stack">
            <h1 className="title">Pick a starting mix</h1>
            <p className="sub">You can add your real mutual funds and stocks next. This just gets you started.</p>
            {([["careful", "Careful", "35% big companies, 60% safe money", Shield],
               ["balanced", "Balanced", "Big companies + everyday brands + some safe money", Scale],
               ["bold", "Bold", "Mostly stocks: big companies, IT, banks, auto", Rocket]] as const).map(([k, t, d, Icon]) => (
              <button key={k} className={`list-row ${mix === k ? "chip on" : ""}`} style={{ width: "100%", textAlign: "left" }} onClick={() => setMix(k)}>
                <span className="row"><Icon size={20} /> <span><b>{t}</b><div className="muted">{d}</div></span></span>
                {mix === k && <span className="pill good">selected</span>}
              </button>
            ))}
            <div className="row between"><button className="btn ghost" onClick={() => setStep(2)}>Back</button>
              <button className="btn" onClick={finish}>Build my plan <Sparkles size={18} /></button></div>
          </div>
        )}
        <p className="disclaimer">Educational tool, not investment advice. Scenarios are simulations, not predictions.</p>
      </div>
    </div>
  );
}
